// Produce one self-contained classic script for the initial server HTML.
// The worker receives this same factory via a Blob; neither path fetches code.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import ts from 'typescript';
import { minify } from 'next/dist/build/swc/index.js';

const root = new URL('../', import.meta.url);
let modules = '';
for (const name of ['color', 'loading-asset', 'loading-orbital']) {
  let source = readFileSync(new URL(`lib/${name}.ts`, root), 'utf8');
  if (name === 'loading-orbital') {
    // GLSL comments live inside string literals, beyond JS minification.
    // This module contains no URLs or regex literals; only shader/host comments.
    source = source.replace(/\/\/[^\n]*/g, '').replace(/\/\*[^]*?\*\//g, '');
  }
  modules += ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, removeComments: true },
  }).outputText.replace(/^import[^]*?from "[^"]+";\n/gm, '').replace(/^export /gm, '');
}
const factory = `function orbitalFactory(canvas, epoch, animate) {\n${modules}\nreturn startLoadingScene(canvas, epoch, animate);\n}`;
const bootstrap = readFileSync(new URL('scripts/loading-bootstrap.js', root), 'utf8');
const { code } = await minify(factory + bootstrap, { compress: { toplevel: true }, mangle: true });
if (/<\/script/i.test(code)) throw new Error('Inline runtime contains a closing script tag');
const output = new URL('lib/loading-runtime.ts', root);
writeFileSync(output, `// Generated by scripts/bake-loading-runtime.mjs. Edit loading-orbital.ts or loading-bootstrap.js.\nexport const LOADING_RUNTIME = ${JSON.stringify(code)};\n`);
console.log(`Loader runtime: ${Buffer.byteLength(code)} bytes, ${gzipSync(code).length} bytes gzip (${fileURLToPath(output)})`);
